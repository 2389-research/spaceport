pub fn find(id: &str) -> Option<Provider> {
    all().find(|provider| provider.id() == id)
}

/// Where `provider` sits in the display list.
pub fn position(provider: Provider) -> usize {
    PROVIDERS
        .iter()
        .position(|meta| meta.id == provider.id())
        .unwrap_or(PROVIDERS.len())
}
